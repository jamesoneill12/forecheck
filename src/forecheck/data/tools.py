"""Catalogue of tools a synthetic scenario can invoke.

Every :class:`~forecheck.contracts.latent.ToolSpec` here is a hand-authored, honest
description of a plausible agent tool: its family, the operation it performs, the
scopes it needs, and the intrinsic properties (communication, financial, authority
changing, irreversible, idempotent) that :mod:`forecheck.data.labeling` reasons about.
"""

from __future__ import annotations

from forecheck.contracts import OperationKind, ResourceKind, ToolFamily, ToolSpec

__all__ = ["TOOL_CATALOGUE", "get_tool", "tools_for_family"]


def _tool(
    name: str,
    family: ToolFamily,
    operation: OperationKind,
    *,
    resource_kind: ResourceKind = ResourceKind.OTHER,
    required_scopes: tuple[str, ...] = (),
    is_communication: bool = False,
    is_financial: bool = False,
    changes_authority: bool = False,
    intrinsically_irreversible: bool = False,
    idempotent: bool = True,
    summary: str = "",
) -> ToolSpec:
    return ToolSpec(
        name=name,
        family=family,
        operation=operation,
        required_scopes=list(required_scopes),
        resource_kind=resource_kind,
        is_communication=is_communication,
        is_financial=is_financial,
        changes_authority=changes_authority,
        intrinsically_irreversible=intrinsically_irreversible,
        idempotent=idempotent,
        summary=summary,
    )


