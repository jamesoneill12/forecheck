_BY_NAME: dict[str, ToolSpec] = {tool.name: tool for tool in TOOL_CATALOGUE}

_BY_FAMILY: dict[ToolFamily, tuple[ToolSpec, ...]] = {
    family: tuple(tool for tool in TOOL_CATALOGUE if tool.family is family) for family in ToolFamily
}


def tools_for_family(family: ToolFamily) -> tuple[ToolSpec, ...]:
    """Return every catalogued tool belonging to ``family``."""
    return _BY_FAMILY[family]


def get_tool(name: str) -> ToolSpec:
    """Look up a tool by its unique name.

    Raises ``KeyError`` naming the tool if it is not in the catalogue.
    """
    if name not in _BY_NAME:
        raise KeyError(f"no tool named {name!r} in the catalogue")
    return _BY_NAME[name]
